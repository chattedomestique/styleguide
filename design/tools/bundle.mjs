#!/usr/bin/env node
/* ==========================================================================
   bundle.mjs — one self-contained page, one CSS file. Zero dependencies.

     node design/tools/bundle.mjs

   Writes to design/dist/ (generated; don't edit):

     flashcards.js      every js/components/*.js: the script elements need.
     flashcards.css     tokens + base + components + wire, imports inlined and
                        wrapped in their layers. What an app links. Fonts stay
                        as files: ../fonts/archivo-latin-var.woff2.
     style-sheet.html   the hub and every element page joined into one page, with
                        the CSS, the font and the script inlined. One file you can
                        email, drop in a chat, or open offline.
     screens.html       screens.html, the same way. The two link to each other.

   Nothing here is needed to USE the sheet. index.html opens straight from disk.
   ========================================================================== */

import { readFileSync, writeFileSync, mkdirSync, statSync, readdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");
const read = (p) => readFileSync(p, "utf8");

/* Inline every @import, wrapping it in its layer if it names one. */
function inlineImports(file) {
  return read(file).replace(
    /@import\s+url\(\s*["']?([^"')]+)["']?\s*\)\s*(?:layer\(\s*([^)]+?)\s*\))?\s*;/g,
    (_, url, layer) => {
      const body = inlineImports(resolve(dirname(file), url)).trim();
      return layer ? `@layer ${layer} {\n${body}\n}` : body;
    },
  );
}

/* Replace url(../fonts/x.woff2) with a data URI. Paths are relative to css/. */
function inlineFonts(css, cssDir) {
  return css.replace(/url\(\s*["']?(\.\.\/fonts\/[^"')]+\.woff2)["']?\s*\)/g, (_, url) => {
    const b64 = readFileSync(resolve(cssDir, url)).toString("base64");
    return `url("data:font/woff2;base64,${b64}")`;
  });
}

const banner = (what) => `/* ${what}. Generated by tools/bundle.mjs, do not edit. */\n`;

mkdirSync(DIST, { recursive: true });

/* 1. the app-facing stylesheet */
const cssEntry = join(ROOT, "css", "flashcards.css");
const bundle = inlineImports(cssEntry);
writeFileSync(join(DIST, "flashcards.css"), banner("flashcards.css") + bundle);

/* 2. the element script: every js/components/*.js, in name order. Each file is
   its own IIFE, so they concatenate safely. */
const JS_DIR = join(ROOT, "js", "components");
const jsBundle = readdirSync(JS_DIR).filter((n) => n.endsWith(".js")).sort()
  .map((n) => read(join(JS_DIR, n)).trim()).join("\n\n") + "\n";
writeFileSync(join(DIST, "flashcards.js"), banner("flashcards.js") + jsBundle);

/* 3. the single-file pages: CSS, the font and sheet.js inlined. */
function inlineAssets(html, baseDir) {
  html = html.replace(/<link rel="stylesheet" href="([^"]+)"\s*\/?>/g, (_, href) => {
    const css = /flashcards\.css$/.test(href) ? bundle : read(resolve(baseDir, href));
    return `<style>\n${inlineFonts(css, join(ROOT, "css"))}\n</style>`;
  });
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => `<script>\n${read(resolve(baseDir, src))}</script>`);
  if (/<link rel="stylesheet"|<script src=/.test(html)) throw new Error("an asset was left un-inlined");
  return html;
}
const stamp = (html, from) =>
  html.replace("<!doctype html>", `<!doctype html>\n<!-- Generated by tools/bundle.mjs from ${from}. Do not edit. -->`);

/* style-sheet.html: the hub, with every element page joined on below it, in the
   hub's order. Links between pages become links within the one page. */
let sheet = read(join(ROOT, "index.html"));
const order = [...sheet.matchAll(/href="elements\/([\w-]+)\.html"/g)].map((m) => m[1]);
const parts = order.map((name) => {
  const page = read(join(ROOT, "elements", `${name}.html`));
  const main = page.match(/<main id="(el-[\w-]+)">([\s\S]*?)<\/main>/);
  if (!main) throw new Error(`elements/${name}.html: no <main id="el-${name}">`);
  return `<section id="${main[1]}">${main[2]}</section>\n`
    .replace(/href="\.\.\/index\.html#([^"]+)"/g, 'href="#$1"')
    .replace(/href="\.\.\/index\.html"/g, 'href="#top"')
    .replace(/href="\.\.\/screens\.html"/g, 'href="screens.html"')
    .replace(/href="([\w-]+)\.html#([^"]+)"/g, 'href="#$2"')
    .replace(/href="([\w-]+)\.html"/g, 'href="#el-$1"');
});
sheet = sheet.replace("    </main>", parts.join("") + "    </main>");
/* the element pages' own <script> tags were outside <main>: carry their code in */
sheet = sheet.replace('    <script src="js/sheet.js"></script>', `    <script>\n${jsBundle}</script>\n    <script src="js/sheet.js"></script>`);
sheet = sheet
  .replace(/href="elements\/[\w-]+\.html#([^"]+)"/g, 'href="#$1"')
  .replace(/href="elements\/([\w-]+)\.html"/g, 'href="#el-$1"');
writeFileSync(join(DIST, "style-sheet.html"), stamp(inlineAssets(sheet, ROOT), "index.html and elements/*.html"));

/* screens.html: links to the hub or an element point into style-sheet.html */
let screens = read(join(ROOT, "screens.html"))
  .replace(/href="index\.html"/g, 'href="style-sheet.html"')
  .replace(/href="elements\/([\w-]+)\.html"/g, 'href="style-sheet.html#el-$1"');
writeFileSync(join(DIST, "screens.html"), stamp(inlineAssets(screens, ROOT), "screens.html"));

const kb = (p) => `${(statSync(p).size / 1024).toFixed(0)} KB`;
console.log(`dist/flashcards.css     ${kb(join(DIST, "flashcards.css"))}`);
console.log(`dist/flashcards.js      ${kb(join(DIST, "flashcards.js"))}`);
console.log(`dist/style-sheet.html   ${kb(join(DIST, "style-sheet.html"))}`);
console.log(`dist/screens.html       ${kb(join(DIST, "screens.html"))}`);
